-- Older clients included the outcome in the event id, so consolidate the rare
-- case where both outcomes were written for one occurrence before enforcing the
-- occurrence-level uniqueness contract. Prefer a confirmed proof.
with ranked as (
  select
    id,
    row_number() over (
      partition by user_id, occurrence_key
      order by (outcome = 'confirmed') desc, resolved_at desc, created_at desc
    ) as rank
  from public.alarm_events
  where occurrence_key is not null
)
delete from public.alarm_events events
using ranked
where events.id = ranked.id and ranked.rank > 1;

